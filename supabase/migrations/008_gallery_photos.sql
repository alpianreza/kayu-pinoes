-- ============================================================================
-- 008 - Tabel galeri foto proses pembuatan (keterangan + urutan tampil).
-- ============================================================================
-- Foto tetap disimpan di bucket "produk" folder gallery/; tabel ini menyimpan
-- datanya: keterangan dan waktu unggah. Foto lama yang sudah ada di folder
-- gallery/ didaftarkan otomatis di bagian akhir (backfill).
-- Aman dijalankan ulang (idempotent).
-- ============================================================================

create table if not exists public.gallery_photos (
  id bigint generated by default as identity primary key,
  storage_path text not null unique,
  caption text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists gallery_photos_created_idx
  on public.gallery_photos (created_at desc, id desc);

alter table public.gallery_photos enable row level security;

drop policy if exists "gallery baca publik" on public.gallery_photos;
create policy "gallery baca publik" on public.gallery_photos
  for select using (true);

drop policy if exists "gallery kelola admin" on public.gallery_photos;
create policy "gallery kelola admin" on public.gallery_photos
  for all using (public.is_admin()) with check (public.is_admin());

-- Daftarkan ulang foto yang sudah ada di Storage (sebelum tabel ini ada).
insert into public.gallery_photos (storage_path, caption)
select o.name, ''
from storage.objects o
where o.bucket_id = 'produk'
  and o.name like 'gallery/%'
  and o.name not like '%.emptyFolderPlaceholder%'
  and o.name ~* '\.(jpe?g|png|webp|gif)$'
on conflict (storage_path) do nothing;

-- Segarkan cache skema PostgREST supaya API langsung mengenal tabel baru.
notify pgrst, 'reload schema';
